#!/usr/bin/env bash
# Regenerates src/sys/*.rs from NVIDIA's public Jetson Multimedia API debs. Needs curl, bsdtar (or GNU tar with zstd) and bindgen 0.72.
set -euo pipefail
cd "$(dirname "$0")"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
repo=https://repo.download.nvidia.com/jetson/common/pool/main/n/nvidia-l4t-jetson-multimedia-api

# module and the deb its headers come from; R35 and R36 share every layout this crate touches (see tests/layouts.rs).
modules=(
    "l4t_r35_r36 nvidia-l4t-jetson-multimedia-api_36.4.7-20250918154033_arm64.deb"
    "l4t_r38 nvidia-l4t-jetson-multimedia-api_38.2.2-20250925153837_arm64.deb"
)

cat > "$work/surface.h" <<'H'
#include <nvbufsurface.h>
H
cat > "$work/transform.h" <<'H'
#include <nvbufsurftransform.h>
H
cat > "$work/jpeg.h" <<'H'
#include <stddef.h>
typedef struct _IO_FILE FILE;
#include <jpeglib.h>
H

for entry in "${modules[@]}"; do
    read -r module deb <<<"$entry"
    dir="$work/$module"
    mkdir -p "$dir"
    curl -fsSL -o "$dir/api.deb" "$repo/$deb"
    (cd "$dir" && tar xf api.deb && tar xf data.tar.*)
    include="$dir/usr/src/jetson_multimedia_api/include"
    clang_args=(--target=aarch64-unknown-linux-gnu -ffreestanding -I"$include" -I"$include/libjpeg-8b")
    common=(--no-doc-comments)
    bindgen "$work/surface.h" "${common[@]}" --dynamic-loading NvBufSurfaceLib \
        --allowlist-function 'NvBufSurface(Allocate|FromFd|Destroy|Map|UnMap|SyncForCpu|SyncForDevice)' \
        --allowlist-type 'NvBufSurface.*' -o "$dir/surface.rs" -- "${clang_args[@]}"
    bindgen "$work/transform.h" "${common[@]}" --dynamic-loading NvBufSurfTransformLib \
        --allowlist-function 'NvBufSurfTransform|NvBufSurfTransformSetSessionParams' \
        --allowlist-type 'NvBufSurfTransform.*' --blocklist-type 'NvBufSurface($|[A-SU-Z].*)' \
        -o "$dir/transform.rs" -- "${clang_args[@]}"
    bindgen "$work/jpeg.h" "${common[@]}" --dynamic-loading NvJpegLib \
        --allowlist-function 'jpeg_(CreateCompress|suppress_tables|mem_dest|set_defaults|set_quality|set_hardware_acceleration_parameters_enc|start_compress|write_raw_data|finish_compress|destroy_compress|std_error)' \
        --allowlist-type 'jpeg_compress_struct|jpeg_error_mgr' -o "$dir/jpeg.rs" -- "${clang_args[@]}"
    {
        echo "//! Generated by generate_bindings.sh (rust-bindgen) from $deb."
        echo
        cat "$dir/surface.rs" "$dir/transform.rs" "$dir/jpeg.rs" | grep -v 'automatically generated by rust-bindgen'
    } > "src/sys/$module.rs"
done
